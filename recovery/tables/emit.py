def _lr_block(demand, left_sheet, left_ranked, right_sheet, right_ranked, limit_pair=None):
    parts = [_lr_band(left_sheet, left_ranked, right_sheet, right_ranked)]
    if limit_pair is not None:
        parts.append("\\par\\vspace{0.45em}")
        parts.append(_lr_band(*limit_pair))
    return "\n".join(parts)


def _lr_band(left_sheet, left_ranked, right_sheet, right_ranked):
    if left_sheet["demand"] != right_sheet["demand"]:
        raise ValueError("left-right band mixes demands")
    quality, tokens, latency = heads(left_sheet["demand"])
    title = "Full ranking" if left_sheet["demand"] == "full" else "LIMIT 10"
    lines = [
        r"\toprule",
        r"\multicolumn{7}{@{}l}{\emph{" + title + r"}} \\",
        r"Method & \multicolumn{3}{c}{Qwen3.5-9B} & \multicolumn{3}{c}{Qwen3.8-27B} \\",
        r"\cmidrule(lr){2-4} \cmidrule(lr){5-7}",
        " & ".join(["", quality, tokens, latency, quality, tokens, latency]) + r" \\",
        r"\midrule",
    ]
    previous = None
    for method in left_sheet["methods"]:
        group = GROUP_OF[method]
        if previous is not None and group != previous:
            lines.append(r"\midrule")
        previous = group
        bits = [row_name(method, left_sheet["demand"])]
        for ranked in (left_ranked, right_ranked):
            for metric in METRICS:
                bits.append(avg_tex(ranked, method, metric))
        lines.append(" & ".join(bits) + r" \\")
    lines.append(r"\bottomrule")
    return tabular("lrrrrrr", lines)


