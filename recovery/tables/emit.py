def load_sheet(path):
    sheet = json.loads(Path(path).read_text())
    check_sheet(sheet)
    return sheet


def check_sheet(sheet):
    if sheet.get("schema") != "sema.exp1.sheet.v1":
        raise ValueError("schema must be sema.exp1.sheet.v1")
    if sheet.get("methods") != list(METHOD_IDS):
        raise ValueError("methods must be the ten-row contract, ListK once and LT once")
    if any(name in sheet["methods"] for name in ("slt", "segmented", "segmented_lt")):
        raise ValueError("SLT is not a row")
    for method in sheet["methods"]:
        for dataset in sheet["datasets"]:
            cell = sheet["cells"][method][dataset]
            for metric in METRICS:
                if "mean" not in cell[metric]:
                    raise ValueError(f"missing mean for {method} {dataset} {metric}")
    return sheet


def decorate(text, mark, math):
    if mark in (None, "none"):
        return text
    if mark == "first":
        if math:
            return "{\\boldmath " + text + "}"
        return "\\textbf{" + text + "}"
    if mark == "second":
        return "\\underline{" + text + "}"
    raise ValueError(mark)


def fmt_quality(mean, std, style, mark):
    shown = f"{mean:.3f}"
    if std is None:
        return decorate(f"${shown}$", mark, math=True)
    std_shown = f"{std:.3f}"
    if style == "inline":
        return decorate(f"${shown}\\pm{std_shown}$", mark, math=True)
    if style == "sub":
        if mark == "second":
            return f"${{\\underline{{{shown}}}}}_{{\\pm{std_shown}}}$"
        if mark == "first":
            return f"{{\\boldmath${shown}_{{\\pm{std_shown}}}$}}"
        return f"${shown}_{{\\pm{std_shown}}}$"
    raise ValueError(style)


def fmt_token(mean):
    return str(int(round(float(mean) / 1000.0)))


def fmt_latency(mean):
    return f"{float(mean):.1f}"


def fmt_rank(value):
    if value is None:
        return "---"
    return f"{value:.2f}"


def metric_tex(sheet, ranked, method, dataset, metric, style):
    raw = sheet["cells"][method][dataset][metric]
    if raw.get("mean") is None:
        return "---"
    mark = ranked["marks"][metric][dataset].get(method, "none")
    if metric == "quality":
        return fmt_quality(raw["mean"], raw.get("permutation_std"), style, mark)
    if metric == "tokens":
        return decorate(fmt_token(raw["mean"]), mark, math=False)
    if metric == "latency":
        return decorate(fmt_latency(raw["mean"]), mark, math=False)
    raise ValueError(metric)


def avg_tex(ranked, method, metric):
    value = ranked["avg"][metric][method]
    if value is None:
        return "---"
    return decorate(fmt_rank(value), ranked["avg_marks"][metric].get(method, "none"), math=False)


def heads(demand):
    quality = r"$\rho$" if demand == "full" else "nDCG"
    return quality, r"\#Tok.", "s"


def exp1_column_spec():
    """Four triplets (three datasets + Avg. Rank) share one width budget."""
    triplet = (
        r">{\centering\arraybackslash}p{0.105\textwidth}"
        r">{\centering\arraybackslash}p{0.048\textwidth}"
        r">{\centering\arraybackslash}p{0.040\textwidth}"
    )
    method = r">{\raggedright\arraybackslash}p{0.17\textwidth}"
    return "@{}" + method + triplet * 4


EXP1_TABCOLSEP = "4pt"


def segment_lines(sheet, ranked, datasets, style, *, avg_block):
    """One band with exactly four 3-column blocks; top band leaves the fourth empty."""
    quality, tokens, latency = heads(sheet["demand"])
    blocks = list(datasets) + ([None] if len(datasets) < 4 else [])
    while len(blocks) < 4:
        blocks.append(None)
    blocks = blocks[:4]
    top = ["Method"]
    sub = [""]
    rules = []
    column = 2
    for block in blocks:
        if block is None and avg_block == "empty":
            top.append(r"\multicolumn{3}{c}{}")
            sub.extend(["", "", ""])
            rules.append(f"\\cmidrule(lr){{{column}-{column + 2}}}")
        elif block is None and avg_block == "data":
            top.append(r"\multicolumn{3}{c}{Avg.\ Rank}")
            sub.extend([quality, tokens, latency])
            rules.append(f"\\cmidrule(lr){{{column}-{column + 2}}}")
        else:
            top.append("\\multicolumn{3}{c}{" + DATASET_HEADER[block] + "}")
            sub.extend([quality, tokens, latency])
            rules.append(f"\\cmidrule(lr){{{column}-{column + 2}}}")
        column += 3
    lines = [
        r"\toprule",
        " & ".join(top) + r" \\",
        " ".join(rules),
        " & ".join(sub) + r" \\",
        r"\midrule",
    ]
    previous = None
    for method in sheet["methods"]:
        group = GROUP_OF[method]
        if previous is not None and group != previous:
            lines.append(r"\midrule")
        previous = group
        bits = [row_name(method, sheet["demand"])]
        for block in blocks:
            if block is None and avg_block == "empty":
                bits.extend(["", "", ""])
            elif block is None and avg_block == "data":
                for metric in METRICS:
                    bits.append(avg_tex(ranked, method, metric))
            elif block is not None:
                for metric in METRICS:
                    bits.append(metric_tex(sheet, ranked, method, block, metric, style))
        lines.append(" & ".join(bits) + r" \\")
    lines.append(r"\bottomrule")
    return lines


def band_lines(sheet, ranked, datasets, style, with_avg):
    """Legacy helper for probe/compare single-band tables."""
    avg = "data" if with_avg else "empty"
    if with_avg and len(datasets) == 3:
        return segment_lines(sheet, ranked, datasets, style, avg_block=avg)
    quality, tokens, latency = heads(sheet["demand"])
    top = ["Method"]
    sub = [""]
    rules = []
    column = 2
    for dataset in datasets:
        top.append("\\multicolumn{3}{c}{" + DATASET_HEADER[dataset] + "}")
        sub.extend([quality, tokens, latency])
        rules.append(f"\\cmidrule(lr){{{column}-{column + 2}}}")
        column += 3
    if with_avg:
        top.append(r"\multicolumn{3}{c}{Avg.\ Rank}")
        sub.extend([quality, tokens, latency])
        rules.append(f"\\cmidrule(lr){{{column}-{column + 2}}}")
    lines = [
        r"\toprule",
        " & ".join(top) + r" \\",
        " ".join(rules),
        " & ".join(sub) + r" \\",
        r"\midrule",
    ]
    previous = None
    for method in sheet["methods"]:
        group = GROUP_OF[method]
        if previous is not None and group != previous:
            lines.append(r"\midrule")
        previous = group
        bits = [row_name(method, sheet["demand"])]
        for dataset in datasets:
            for metric in METRICS:
                bits.append(metric_tex(sheet, ranked, method, dataset, metric, style))
        if with_avg:
            for metric in METRICS:
                bits.append(avg_tex(ranked, method, metric))
        lines.append(" & ".join(bits) + r" \\")
    lines.append(r"\bottomrule")
    return lines


def tabular_block(spec, lines):
    return "\\begin{tabular}{%s}\n%s\n\\end{tabular}" % (spec, "\n".join(lines))


def tabular(spec, lines):
    return tabular_block(spec, lines)


def table_star(caption, label, inner, tabcolsep=EXP1_TABCOLSEP, body_size=r"\small"):
    return (
        "\\begin{table*}[t]\n"
        "\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{" + label + "}\n"
        "\\begingroup\n"
        + body_size
        + "\n\\setlength{\\tabcolsep}{" + tabcolsep + "}\n"
        "\\renewcommand{\\arraystretch}{1.06}\n"
        + inner
        + "\n\\endgroup\n"
        "\\end{table*}\n"
    )


def table_column(caption, label, inner, size=r"\footnotesize", tabcolsep="3pt"):
    return (
        "\\begin{table}[t]\n"
        "\\centering\n"
        "\\caption{" + caption + "}\n"
        "\\label{" + label + "}\n"
        + size
        + "\n\\setlength{\\tabcolsep}{" + tabcolsep + "}\n"
        + inner
        + "\n\\end{table}\n"
    )


