"""Turn an E1 JSON sheet into includable LaTeX.

Schema sema.exp1.sheet.v1, one object per model and demand:

    schema, synthetic, model, demand, quality_metric,
    token_unit, token_display, latency_unit,
    datasets, methods,
    cells[method][dataset][quality|tokens|latency]

quality: mean, permutation_std, n_permutations. mean null is a missing cell.
tokens and latency: mean, n_repeats, repeat_variance.
repeat_variance is ignored unless n_repeats >= 2, and it is never printed.
Token and latency cells have no \\pm. Quality \\pm is the permutation std.

    python3 emit.py --write-checkpoint
    python3 emit.py --sheet data/Qwen3.5-9B-full.json --out /tmp/one.tex

The checkpoint TeX is synthetic. A measured sheet with synthetic=false
keeps the same column rules and drops the synthetic sentence.
"""

