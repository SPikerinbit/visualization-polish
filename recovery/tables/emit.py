def write_checkpoint(root=ROOT):
    root = Path(root)
    sheets = build_all()
    data_dir = root / "data"
    tex_dir = root / "tex"
    probe_dir = root / "probe"
    data_dir.mkdir(parents=True, exist_ok=True)
    tex_dir.mkdir(parents=True, exist_ok=True)
    ranked = { _key(sheet): (sheet, rank_sheet(sheet)) for sheet in sheets }
    for sheet in sheets:
        name = sheet["model"] + "-" + sheet["demand"] + ".json"
        data_dir.joinpath(name).write_text(json.dumps(sheet, indent=2) + "\n")
    full = []
    limit = []
    for sheet in sheets:
        body = GENERATED + emit_stacked(sheet)
        if sheet["demand"] == "full":
            full.append(body)
        else:
            limit.append(body)
    note = (
        "% Historical labels: tab:exp1-full and tab:exp1-topk on the 9B tables.\n"
        "% tab:exp1-full-27b and tab:exp1-topk-27b are suggestions and are not approved.\n"
    )
    tex_dir.joinpath("exp1-full.tex").write_text(note + "\n".join(full))
    tex_dir.joinpath("exp1-limit10.tex").write_text(note + "\n".join(limit))
    tex_dir.joinpath("exp1-compare.tex").write_text(GENERATED + emit_compare_file(ranked))
    tex_dir.joinpath("tab-datasets.tex").write_text(GENERATED + datasets_tex())
    tex_dir.joinpath("tab-ranking-algorithms.tex").write_text(GENERATED + algorithms_tex())
    tex_dir.joinpath("tab-params-full.tex").write_text(GENERATED + params_tex())
    tex_dir.joinpath("tab-exp4-validation.tex").write_text(GENERATED + validation_tex())
    tex_dir.joinpath("tab-symbols-dormant.tex").write_text(symbols_dormant_tex())
    nine = next(sheet for sheet in sheets if sheet["model"] == "Qwen3.5-9B" and sheet["demand"] == "full")
    probe_dir.joinpath("wide-inline.tex").write_text(GENERATED + emit_wide(nine, "inline"))
    probe_dir.joinpath("wide-sub.tex").write_text(GENERATED + emit_wide(nine, "sub"))
    return sheets


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write-checkpoint", action="store_true")
    parser.add_argument("--sheet", type=Path)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--style", choices=("inline", "sub"), default="inline")
    args = parser.parse_args()
    if args.write_checkpoint:
        write_checkpoint()
        return
    if args.sheet is None or args.out is None:
        parser.error("pass --write-checkpoint or both --sheet and --out")
    sheet = load_sheet(args.sheet)
    args.out.write_text(GENERATED + emit_stacked(sheet, style=args.style))


if __name__ == "__main__":
    main()
